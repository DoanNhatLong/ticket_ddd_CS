CREATE DATABASE IF NOT EXISTS `0test1` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `0test1`;

SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS Payments;
DROP TABLE IF EXISTS BookingItems; -- legacy name of Tickets
DROP TABLE IF EXISTS Tickets;
DROP TABLE IF EXISTS Bookings;
DROP TABLE IF EXISTS Users;
DROP TABLE IF EXISTS TripSeatPrices; -- legacy name of Fares
DROP TABLE IF EXISTS Fares;
DROP TABLE IF EXISTS Seats;
DROP TABLE IF EXISTS SeatClasses;
DROP TABLE IF EXISTS Carriages;
DROP TABLE IF EXISTS TrainTrips;
DROP TABLE IF EXISTS Trains;
DROP TABLE IF EXISTS Routes;
DROP TABLE IF EXISTS Stations;
SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE Stations (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    Code VARCHAR(10) NOT NULL UNIQUE,
    Name VARCHAR(100) NOT NULL,
    City VARCHAR(100) NOT NULL,
    CreatedAt DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE Routes (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    DepartureStationId INT NOT NULL,
    ArrivalStationId INT NOT NULL,
    DistanceKm DECIMAL(8, 2) NOT NULL,
    CONSTRAINT FK_Routes_DepartureStation FOREIGN KEY (DepartureStationId) REFERENCES Stations(Id) ON DELETE RESTRICT,
    CONSTRAINT FK_Routes_ArrivalStation FOREIGN KEY (ArrivalStationId) REFERENCES Stations(Id) ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE Trains (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    Code VARCHAR(20) NOT NULL UNIQUE,
    Name VARCHAR(100) NOT NULL,
    TotalCapacity INT NOT NULL,
    CreatedAt DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE Carriages (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    TrainId INT NOT NULL,
    CarriageNumber INT NOT NULL,
    Type VARCHAR(50) NOT NULL,
    TotalSeats INT NOT NULL,
    CONSTRAINT FK_Carriages_Train FOREIGN KEY (TrainId) REFERENCES Trains(Id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- Seat class: the kind of place a seat offers; the only thing that sets a seat's price.
CREATE TABLE SeatClasses (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    Code VARCHAR(30) NOT NULL UNIQUE,
    Name VARCHAR(100) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE Seats (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    CarriageId INT NOT NULL,
    SeatNumber VARCHAR(10) NOT NULL,
    SeatClassId INT NOT NULL,
    CONSTRAINT FK_Seats_Carriage FOREIGN KEY (CarriageId) REFERENCES Carriages(Id) ON DELETE CASCADE,
    CONSTRAINT FK_Seats_SeatClass FOREIGN KEY (SeatClassId) REFERENCES SeatClasses(Id) ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE TrainTrips (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    TrainId INT NOT NULL,
    RouteId INT NOT NULL,
    DepartureTime DATETIME NOT NULL,
    ArrivalTime DATETIME NOT NULL,
    Status ENUM('Scheduled', 'Delayed', 'Completed', 'Cancelled') NOT NULL DEFAULT 'Scheduled',
    CreatedAt DATETIME DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_TrainTrips_Train FOREIGN KEY (TrainId) REFERENCES Trains(Id) ON DELETE CASCADE,
    CONSTRAINT FK_TrainTrips_Route FOREIGN KEY (RouteId) REFERENCES Routes(Id) ON DELETE RESTRICT
) ENGINE=InnoDB;

-- Fare: the price a train trip asks for one seat class.
CREATE TABLE Fares (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    TrainTripId INT NOT NULL,
    SeatClassId INT NOT NULL,
    Price DECIMAL(10, 2) NOT NULL,
    CONSTRAINT UQ_Fares_TrainTrip_SeatClass UNIQUE (TrainTripId, SeatClassId),
    CONSTRAINT FK_Fares_TrainTrip FOREIGN KEY (TrainTripId) REFERENCES TrainTrips(Id) ON DELETE CASCADE,
    CONSTRAINT FK_Fares_SeatClass FOREIGN KEY (SeatClassId) REFERENCES SeatClasses(Id) ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE Users (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    Email VARCHAR(255) NOT NULL UNIQUE,
    PasswordHash VARCHAR(255) NOT NULL,
    FullName VARCHAR(100) NOT NULL,
    PhoneNumber VARCHAR(20) NOT NULL,
    Role VARCHAR(50) NOT NULL DEFAULT 'Customer',
    CreatedAt DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE Bookings (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    UserId INT NOT NULL,
    BookingCode VARCHAR(50) NOT NULL UNIQUE,
    TotalAmount DECIMAL(12, 2) NOT NULL,
    Status VARCHAR(50) NOT NULL DEFAULT 'Pending',
    CreatedAt DATETIME DEFAULT CURRENT_TIMESTAMP,
    ExpiresAt DATETIME NOT NULL,
    CONSTRAINT FK_Bookings_User FOREIGN KEY (UserId) REFERENCES Users(Id) ON DELETE RESTRICT
) ENGINE=InnoDB;

-- Ticket: the right for one passenger to occupy one seat on one train trip.
-- Status: Held (booking unpaid) | Active (paid) | Cancelled | Used.
-- OccupiedSeatKey is generated by MySQL: '<TrainTripId>:<SeatId>' while the ticket holds its seat
-- (Held or Active), NULL otherwise. Its unique index is what prevents selling a seat twice.
CREATE TABLE Tickets (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    BookingId INT NOT NULL,
    TrainTripId INT NOT NULL,
    SeatId INT NOT NULL,
    PassengerName VARCHAR(100) NOT NULL,
    PassengerIdNumber VARCHAR(20) NOT NULL,
    Price DECIMAL(10, 2) NOT NULL,
    Status VARCHAR(20) NOT NULL DEFAULT 'Held',
    OccupiedSeatKey VARCHAR(30) AS (
        CASE WHEN Status IN ('Held', 'Active') THEN CONCAT(TrainTripId, ':', SeatId) END
    ) STORED,
    CONSTRAINT UQ_Tickets_OccupiedSeatKey UNIQUE (OccupiedSeatKey),
    CONSTRAINT FK_Tickets_Booking FOREIGN KEY (BookingId) REFERENCES Bookings(Id) ON DELETE CASCADE,
    CONSTRAINT FK_Tickets_TrainTrip FOREIGN KEY (TrainTripId) REFERENCES TrainTrips(Id) ON DELETE RESTRICT,
    CONSTRAINT FK_Tickets_Seat FOREIGN KEY (SeatId) REFERENCES Seats(Id) ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE Payments (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    BookingId INT NOT NULL,
    TransactionId VARCHAR(100) NOT NULL UNIQUE,
    Amount DECIMAL(12, 2) NOT NULL,
    PaymentMethod VARCHAR(50) NOT NULL,
    Status VARCHAR(50) NOT NULL DEFAULT 'Pending',
    PaidAt DATETIME NULL,
    CONSTRAINT FK_Payments_Booking FOREIGN KEY (BookingId) REFERENCES Bookings(Id) ON DELETE CASCADE
) ENGINE=InnoDB;

