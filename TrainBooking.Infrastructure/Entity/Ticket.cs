using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;
using Microsoft.EntityFrameworkCore;

namespace TrainBooking.Infrastructure.Entity;

[Table("Tickets")]
[Index("BookingId", Name = "FK_Tickets_Booking")]
[Index("SeatId", Name = "FK_Tickets_Seat")]
[Index("TrainTripId", Name = "FK_Tickets_TrainTrip")]
[Index("OccupiedSeatKey", Name = "UQ_Tickets_OccupiedSeatKey", IsUnique = true)]
public partial class Ticket
{
    [Key]
    public int Id { get; set; }

    public int BookingId { get; set; }

    public int TrainTripId { get; set; }

    public int SeatId { get; set; }

    [StringLength(100)]
    public string PassengerName { get; set; } = null!;

    [StringLength(20)]
    public string PassengerIdNumber { get; set; } = null!;

    [Precision(10, 2)]
    public decimal Price { get; set; }

    [StringLength(20)]
    public string Status { get; set; } = null!;

    /// <summary>
    /// Generated by MySQL from Status, TrainTripId and SeatId; never written by the application.
    /// </summary>
    [StringLength(30)]
    public string? OccupiedSeatKey { get; set; }

    [ForeignKey("BookingId")]
    [InverseProperty("Tickets")]
    public virtual Booking Booking { get; set; } = null!;

    [ForeignKey("SeatId")]
    [InverseProperty("Tickets")]
    public virtual Seat Seat { get; set; } = null!;

    [ForeignKey("TrainTripId")]
    [InverseProperty("Tickets")]
    public virtual Traintrip TrainTrip { get; set; } = null!;
}
